#include <iostream>
using namespace std;
int main() {

    //Array

    int marks [5] = {99, 100, 54, 36, 88};

    int size = 5; //array size

    cout << marks [0] << endl; //To print the value of the 0th position of array

    //Loops in array

    for (int i = 0; i<size; i++){
        cout << marks[i] << endl;
    }
}